/**
 * Computes strictly verified statistics directly from the registry.
 * This guarantees the landing page and directory NEVER display fake numbers.
 */
export function getRegistryStatistics() {
  const all = Object.values(RUNTIME_REGISTRY);
  const verifiedList = all.filter((r) => r.verificationStatus === 'PASS');
  const availableList = all.filter((r) => r.status === 'available');

  const languages = all.filter((r) => r.type === 'language');
  const runtimes = all.filter((r) => r.type === 'runtime');
  const frameworks = all.filter((r) => r.type === 'framework');
  const databases = all.filter((r) => r.type === 'database');
  const tools = all.filter((r) => r.type === 'tool' || r.type === 'compiler' || r.type === 'interpreter' || r.type === 'shell');
  const webEnvironments = all.filter((r) => r.type === 'web environment');

  const multiFileVerified = verifiedList.filter((r) => r.verifiedCapabilities.multiFile);
  const packageVerified = verifiedList.filter((r) => r.verifiedCapabilities.packages);
  const testVerified = verifiedList.filter((r) => r.verifiedCapabilities.test);

  return {
    totalTargetBenchmark: 114,
    totalRegisteredEnvironments: all.length,
    verifiedCount: verifiedList.length,
    availableCount: availableList.length,
    passCount: verifiedList.length,
    notImplementedCount: all.filter((r) => r.verificationStatus === 'NOT_IMPLEMENTED').length,
    failedCount: all.filter((r) => r.verificationStatus === 'FAIL').length,
    blockedCount: all.filter((r) => r.verificationStatus === 'BLOCKED').length,
    languagesCount: languages.length,
    runtimesCount: runtimes.length,
    frameworksCount: frameworks.length,
    databasesCount: databases.length,
    toolsCount: tools.length,
    webEnvironmentsCount: webEnvironments.length,
    multiFileVerifiedCount: multiFileVerified.length,
    packageVerifiedCount: packageVerified.length,
    testVerifiedCount: testVerified.length,
    verifiedList: verifiedList.map((r) => ({ id: r.id, name: r.name, version: r.version, type: r.type })),
  };
}
