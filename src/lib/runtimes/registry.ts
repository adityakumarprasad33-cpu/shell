/**
 * Runix Universal Runtime & Language Registry
 * Central machine-readable registry for all 114 market benchmark environments.
 * 
 * Strict engineering rule:
 * DO NOT DISPLAY OR CLAIM A CAPABILITY THAT HAS NOT BEEN ACTUALLY IMPLEMENTED AND VERIFIED.
 * A runtime is supported only after real execution/build verification.
 */

export type LanguageClassification =
  | 'language'
  | 'runtime'
  | 'framework'
  | 'database'
  | 'web environment'
  | 'shell'
  | 'tool'
  | 'compiler'
  | 'interpreter'
  | 'project environment';

export type RuntimeStatus =
  | 'available'
  | 'experimental'
  | 'beta'
  | 'comingSoon'
  | 'unavailable'
  | 'deprecated';

export type VerificationState =
  | 'PASS'
  | 'FAIL'
  | 'BLOCKED'
  | 'NOT_IMPLEMENTED'
  | 'N/A';

export interface VerifiedCapabilities {
  run: boolean;
  build: boolean;
  test: boolean;
  debug: boolean;
  multiFile: boolean;
  packages: boolean;
  stdin: boolean;
  network: boolean;
  gui: boolean;
  database: boolean;
  crossCompile: boolean;
}

export interface VerificationEvidence {
  testId: string;
  command: string;
  stdout: string;
  stderr?: string;
  exitCode: number;
  durationMs: number;
  timestamp: string;
}

export interface RuntimeDefinition {
  id: string;
  name: string;
  type: LanguageClassification;
  version: string;
  extensions: string[];
  filenames: string[];
  mimeTypes: string[];
  runtime?: string;
  compiler?: string;
  interpreter?: string;
  buildCommand?: string;
  runCommand?: string;
  testCommand?: string;
  debugCommand?: string;
  debugger?: string;
  packageManager?: string;
  multiFileSupport: boolean;
  stdinSupport: boolean;
  stdoutSupport: boolean;
  stderrSupport: boolean;
  networkPolicy: 'restricted' | 'standard' | 'open';
  resourceProfile: {
    cpuLimit: string;
    memoryLimit: string;
    timeoutSec: number;
  };
  supportedArchitectures: string[];
  supportedOperatingSystems: string[];
  projectType: string;
  status: RuntimeStatus;
  verificationStatus: VerificationState;
  verifiedCapabilities: VerifiedCapabilities;
  lastVerifiedAt?: string;
  verificationEvidence?: VerificationEvidence;
  description: string;
}

